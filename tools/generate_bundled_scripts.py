#!/usr/bin/env python3
"""Regenerate src/core/sb_bundled_scripts.e from the pinned scripts in assets/.

simple_browser bundles htmx and Alpine.js (SIMPLE_BROWSER_SPEC.md 4.9): the minified
files and their licenses live in assets/, named with their versions, and the class
SB_BUNDLED_SCRIPTS holds each file's text (in constants of at most 30000
characters, joined once) and version as constants, so nothing is read
at run time.

To move to a new version: put the new minified file in assets/ in place of the old one
(htmx-<version>.min.js, alpinejs-<version>.min.js), update its license file, run

    python3 tools/generate_bundled_scripts.py

from the library's folder, name the new version in the spec and the README, and update
the version the test `htmx_and_alpine_load_without_the_network' expects.
"""

import hashlib
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
ASSETS = ROOT / "assets"
TARGET = ROOT / "src" / "core" / "sb_bundled_scripts.e"
CHUNK = 96


def find_one(pattern):
    """The single asset matching `pattern', with the version its name carries."""
    matches = sorted(ASSETS.glob(pattern))
    if len(matches) != 1:
        sys.exit(f"expected exactly one assets/{pattern}, found {len(matches)}")
    found = re.search(r"-(\d+\.\d+\.\d+)\.min\.js$", matches[0].name)
    if not found:
        sys.exit(f"no version in {matches[0].name}")
    return matches[0], found.group(1)


def escape(char):
    """One character as it is written inside an Eiffel manifest string."""
    code = ord(char)
    if char == "%":
        return "%%"
    if char == '"':
        return '%"'
    if char == "\n":
        return "%N"
    if char == "\r":
        return "%R"
    if char == "\t":
        return "%T"
    if code < 32 or code == 127:
        return f"%/{code}/"
    if code > 127:
        sys.exit("the bundled scripts are expected to be ASCII")
    return char


def constant(name, text, comment):
    """An Eiffel manifest string constant holding `text', split over continued lines."""
    pieces = [escape(c) for c in text]
    lines = []
    current = ""
    for piece in pieces:
        if len(current) + len(piece) > CHUNK:
            lines.append(current)
            current = ""
        current += piece
    lines.append(current)
    out = [f'\t{name}: STRING_8 = "{lines[0]}']
    for line in lines[1:]:
        out[-1] += "%"
        out.append(f"\t\t%{line}")
    out[-1] += '"'
    out.append(f"\t\t\t-- {comment}")
    return "\n".join(out)


PART = 30000  # characters per manifest string: the Eiffel compiler takes at most 32767


def script(name, text, file_name):
    """`name' as a once function joining constants of at most PART characters each."""
    parts = [text[i:i + PART] for i in range(0, len(text), PART)]
    out = [f"\t{name}: STRING_8",
           f"\t\t\t-- assets/{file_name}, whole ({len(text)} characters).",
           "\t\tonce",
           f"\t\t\tcreate Result.make ({len(text)})"]
    for index in range(1, len(parts) + 1):
        out.append(f"\t\t\tResult.append ({name}_part_{index})")
    out.append("\t\tensure")
    out.append(f"\t\t\tall_there: Result.count = {len(text)}")
    out.append("\t\tend")
    constants = [constant(f"{name}_part_{index}", part,
                          f"Part {index} of {len(parts)} of assets/{file_name}.")
                 for index, part in enumerate(parts, start=1)]
    return "\n".join(out), "\n\n".join(constants)


def main():
    htmx_file, htmx_version = find_one("htmx-*.min.js")
    alpine_file, alpine_version = find_one("alpinejs-*.min.js")
    htmx = htmx_file.read_bytes()
    alpine = alpine_file.read_bytes()
    htmx_text = htmx.decode("ascii")
    alpine_text = alpine.decode("ascii")
    for label, text in (("htmx", htmx_text), ("Alpine.js", alpine_text)):
        if "</script" in text.lower():
            sys.exit(f"{label} holds </script and cannot be written inline")
    htmx_once, htmx_parts = script("Htmx_script", htmx_text, htmx_file.name)
    alpine_once, alpine_parts = script("Alpine_script", alpine_text, alpine_file.name)
    body = f'''note
	description: "[
		SB_BUNDLED_SCRIPTS - htmx {htmx_version} and Alpine.js {alpine_version}, pinned and bundled
		(SIMPLE_BROWSER_SPEC.md 4.9). SIMPLE_BROWSER.load_htmx_page writes them inline.

		GENERATED by tools/generate_bundled_scripts.py from assets/; do not edit by hand.
		Licenses: assets/LICENSE-htmx (Zero-Clause BSD), assets/LICENSE-alpinejs (MIT).
	]"

class
	SB_BUNDLED_SCRIPTS

feature -- Versions

	Htmx_version: STRING_8 = "{htmx_version}"
			-- The bundled htmx.

	Alpine_version: STRING_8 = "{alpine_version}"
			-- The bundled Alpine.js.

feature -- Integrity

	Htmx_sha256: STRING_8 = "{hashlib.sha256(htmx).hexdigest()}"
			-- SHA-256 of assets/{htmx_file.name}.

	Alpine_sha256: STRING_8 = "{hashlib.sha256(alpine).hexdigest()}"
			-- SHA-256 of assets/{alpine_file.name}.

	Htmx_size: INTEGER = {len(htmx)}
			-- Bytes in assets/{htmx_file.name}.

	Alpine_size: INTEGER = {len(alpine)}
			-- Bytes in assets/{alpine_file.name}.

feature -- Scripts

{htmx_once}

{alpine_once}

feature {{NONE}} -- Parts (a manifest string holds at most 32767 characters)

{htmx_parts}

{alpine_parts}

end
'''
    TARGET.write_bytes(body.replace("\n", "\r\n").encode("ascii"))
    print(f"wrote {TARGET.relative_to(ROOT)}: htmx {htmx_version} ({len(htmx)} bytes), "
          f"Alpine.js {alpine_version} ({len(alpine)} bytes)")


if __name__ == "__main__":
    main()
